const base=process.env.TUTORMATCHING_API_URL??'http://localhost:8080/api/v1';
let assertions=0;
async function api(path,token,method='GET',data,status=200){
 const response=await fetch(base+path,{method,headers:{...(token?{Authorization:'Bearer '+token}:{}),...(data?{'Content-Type':'application/json'}:{})},body:data?JSON.stringify(data):undefined});
 const raw=await response.text();assert.equal(response.status,status,method+' '+path+': '+raw.slice(0,200));assertions++;
 return raw?JSON.parse(raw):null;
}
